#!/usr/bin/env python3
"""Refresh progressive-enhancement fallbacks and contextual links.

Run after editing articles.js. No external requests; requires Python 3.10+.
The runtime archive components and this script use the same section ID set.
"""
from pathlib import Path
import datetime, hashlib, html, json, re
from html.parser import HTMLParser
from editorial_topics import GROUPS, ANCHORS, RELATED

ROOT = Path(__file__).resolve().parents[1]
class Links(HTMLParser):
    def __init__(self):super().__init__();self.links=[]
    def handle_starttag(self,tag,attrs):
        if tag=='a':self.links.append(dict(attrs).get('href',''))
def escape(value):return html.escape(str(value),quote=True)
def replace_container(text,identity,content):
    # Cards contain nested divs, so find the matching closing div by depth.
    start=re.search(r'<div\b[^>]*\bid="'+re.escape(identity)+r'"[^>]*>',text)
    if not start:raise ValueError('Missing '+identity)
    depth=1
    for tag in re.finditer(r'</?div\b[^>]*>',text[start.end():],re.I):
        depth += -1 if tag.group().startswith('</') else 1
        if depth==0:
            end=start.end()+tag.start()
            return text[:start.end()]+content+text[end:]
    raise ValueError('Unclosed '+identity)
def marked(text,key,content):
    block=f'<!-- {key}:start -->\n{content}\n<!-- {key}:end -->'
    pattern=r'<!-- '+key+r':start -->.*?<!-- '+key+r':end -->'
    return re.sub(pattern,lambda m:block,text,flags=re.S) if re.search(pattern,text,re.S) else None

def refresh():
    articles=json.loads((ROOT/'articles.js').read_text().split('=',1)[1].strip().removesuffix(';'))
    byid={a['id']:a for a in articles}
    tech_source=(ROOT/'tech-ai.js').read_text().split('new Set([',1)[1].split(']);',1)[0]
    tech=set(re.findall(r'"([a-z0-9-]+)"',tech_source))
    def dates(article):
        value=datetime.datetime.fromisoformat(article['date'])
        if value.tzinfo is None:value=value.replace(tzinfo=datetime.timezone.utc)
        return value.astimezone(datetime.timezone.utc)
    latest=sorted(articles,key=dates,reverse=True)
    card_keys={'id','section','title','dek','imageAlt','author','date','tickers','image','imageSmall','imageMedium','imageSrcset'}
    cards=[{k:v for k,v in a.items() if k in card_keys} for a in articles]
    (ROOT/'article-cards.js').write_text('/* Generated by scripts/refresh_static_editorial.py; full text lives on article pages. */\nconst TTN_ARTICLES = '+json.dumps(cards,ensure_ascii=False,separators=(',',':'))+';\n')
    card_version=hashlib.sha256((ROOT/'article-cards.js').read_bytes()).hexdigest()[:12]
    groups={k:[i for i in ids if i in byid] for k,ids in GROUPS.items()}
    assigned=[i for ids in groups.values() for i in ids]
    assert len(set(assigned))==len(assigned),'Duplicate topic assignment'
    # New material still appears in the full static archive before topic review.
    unassigned=[a['id'] for a in articles if a['id'] not in assigned]
    if unassigned:groups['More reporting']=unassigned
    topics={i:k for k,ids in groups.items() for i in ids}
    for a in articles:
        page=ROOT/(a['id']+'.html');text=page.read_text()
        if 'class="editorial-related"' in text:continue
        selected=[]
        # Preserve older, explicit editorial reading recommendations.
        for paragraph in re.findall(r'<p\b[^>]*>\s*Related reading:.*?</p>',text,re.S|re.I):
            links=Links();links.feed(paragraph)
            selected.extend(href.removesuffix('.html') for href in links.links if href.endswith('.html') and href.removesuffix('.html') in byid)
            text=text.replace(paragraph,'')
        candidates=RELATED.get(a['id'],[])+ANCHORS.get(topics[a['id']],[])+groups[topics[a['id']]]
        for candidate in candidates:
            if candidate!=a['id'] and candidate in byid and candidate not in selected:selected.append(candidate)
        selected=[i for i in dict.fromkeys(selected) if i!=a['id']][:3]
        assert len(selected)==3,(a['id'],selected)
        links=''.join(f'<li><a href="{escape(i)}.html">{escape(byid[i]["title"])}</a></li>' for i in selected)
        block='<aside class="editorial-related" aria-labelledby="related-reading-title"><h2 id="related-reading-title">Related reading</h2><ul>'+links+'</ul></aside>'
        text=text.replace('</main>',block+'\n</main>',1)
        if 'editorial-related.css' not in text:text=text.replace('</head>','<link rel="stylesheet" href="editorial-related.css?v=audit-20261018">\n</head>')
        page.write_text(text)

    def card(a,section):
        image=escape(a.get('imageSmall') or a['image']);srcset=a.get('imageSrcset')
        responsive=f' srcset="{escape(srcset)}" sizes="(max-width:700px) calc(100vw - 40px), 400px"' if srcset else ''
        label=datetime.datetime.fromisoformat(a['date']).strftime('%b %d, %Y').replace(' 0',' ')
        return f'<article class="editorial-archive-card"><a class="editorial-archive-media" href="{a["id"]}.html"><img src="{image}"{responsive} alt="{escape(a.get("imageAlt") or a["title"])}" width="640" height="360" loading="lazy" decoding="async"></a><div class="editorial-archive-content"><span class="ttn-original-badge">{escape(section)}</span><h3><a href="{a["id"]}.html">{escape(a["title"])}</a></h3><p class="editorial-dek">{escape(a["dek"])}</p><div class="editorial-meta"><span class="editorial-author">{escape(a.get("author") or "TTN Research Desk")}</span><time datetime="{escape(a["date"])}">{label}</time></div></div></article>'
    for filename,identity,is_tech in [('analysis.html','analysis-archive',False),('tech-ai.html','tech-ai-archive',True)]:
        page=ROOT/filename;text=page.read_text();items=[a for a in latest if (a['id'] in tech)==is_tech];ids={a['id'] for a in items}
        text=replace_container(text,identity,''.join(card(a,'Tech & AI' if is_tech else 'Market Analysis') for a in items[:12]))
        directory='<section class="editorial-topics" aria-labelledby="browse-topics-title"><h2 id="browse-topics-title">Browse by topic</h2><p>Reporting and explainers from the full archive.</p>'
        for topic,groupids in groups.items():
            entries=sorted((byid[i] for i in groupids if i in ids),key=dates,reverse=True)
            if entries:
                directory+=f'<details><summary>{escape(topic)} <span>({len(entries)})</span></summary><ul>'+''.join(f'<li><a href="{a["id"]}.html">{escape(a["title"])}</a></li>' for a in entries)+'</ul></details>'
        directory+='</section>'
        replacement=marked(text,'editorial-topics',directory)
        if replacement is None:text=text.replace('</main>','<!-- editorial-topics:start -->\n'+directory+'\n<!-- editorial-topics:end -->\n</main>')
        else:text=replacement
        if 'editorial-related.css' not in text:text=text.replace('</head>','<link rel="stylesheet" href="editorial-related.css?v=audit-20261018">\n</head>')
        # The archives neither initialize nor display the external news feed.
        text=re.sub(r'<script\b[^>]*src="(?:news|config)\.js[^\"]*"[^>]*></script>\s*','',text)
        page.write_text(text)
    page=ROOT/'index.html';text=page.read_text()
    for identity,is_tech in [('ttn-articles',False),('tech-ai-home',True)]:
        items=[a for a in latest if (a['id'] in tech)==is_tech][:4]
        text=replace_container(text,identity,''.join(card(a,'Tech & AI' if is_tech else 'Market Analysis') for a in items))
    fallback='<noscript><section class="editorial-nojs" aria-labelledby="nojs-latest"><h2 id="nojs-latest">Latest original reporting</h2><p>Live quotes and the external news feed require JavaScript. TTN articles and topic archives remain available below.</p><ul>'+''.join(f'<li><a href="{a["id"]}.html">{escape(a["title"])}</a></li>' for a in latest[:12])+'</ul></section></noscript>'
    replacement=marked(text,'editorial-nojs',fallback)
    if replacement is None:
        text=text.replace('<main class="container home-layout">','<main class="container home-layout">\n<h1 class="home-heading">Financial news, market analysis and technology</h1>\n<!-- editorial-nojs:start -->\n'+fallback+'\n<!-- editorial-nojs:end -->')
        text=text.replace('</head>','<noscript><style>.home-top-row,.home-news-row{display:none}</style></noscript>\n<link rel="stylesheet" href="editorial-related.css?v=audit-20261018">\n</head>')
    else:text=replacement
    page.write_text(text)
    # Cards do not need to download the text of every article. Standalone
    # article pages already contain their complete content and ticker tags.
    for page in ROOT.glob('*.html'):
        text=page.read_text();old=text
        if page.name in {'index.html','analysis.html','tech-ai.html'}:
            text=re.sub(r'(?:articles|article-cards)\.js(?:\?[^"\s>]*)?','article-cards.js?v='+card_version,text)
        else:
            text=re.sub(r'<script\b[^>]*src="articles\.js[^\"]*"[^>]*></script>\s*','',text)
            if page.stem in byid:
                text=re.sub(r'<script\b[^>]*src="config\.js[^\"]*"[^>]*></script>\s*','',text)
        if text!=old:page.write_text(text)
    print(f'Refreshed {len(articles)} article links, two full topic archives and homepage fallbacks.')
if __name__=='__main__':refresh()
